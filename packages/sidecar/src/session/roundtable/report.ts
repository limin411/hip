interface TocItem {
  id: string
  label: string
  depth: 1 | 2
}

function esc(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function proseHtml(s: string): string {
  return esc(s).replace(/\n/g, '<br/>')
}

function bullets(items: string[]): string {
  if (!items.length) return '<li class="muted">—</li>'
  return items.map((x) => `<li>${esc(x)}</li>`).join('\n')
}

function roundHeading(lang: RoundtableLang, n: number): string {
  const L = LABELS[lang]
  if (lang === 'zh-CN' || lang === 'zh-TW') return `${L.round} ${n} 轮`
  if (lang === 'ja') return `${L.round} ${n}`
  if (lang === 'ko') return `${L.round} ${n}`
  return `${L.round} ${n}`
}

function edgeRel(lang: RoundtableLang, rel: string): string {
  if (lang === 'zh-CN' || lang === 'zh-TW') {
    if (rel === 'rebut') return '反驳'
    if (rel === 'support') return '附议'
    return '提问'
  }
  if (lang === 'ja') {
    if (rel === 'rebut') return '反論'
    if (rel === 'support') return '支持'
    return '質問'
  }
  if (lang === 'ko') {
    if (rel === 'rebut') return '반박'
    if (rel === 'support') return '지지'
    return '질문'
  }
  return rel
}

function personaName(id: string, lang: RoundtableLang): string {
  if ((['strategist', 'skeptic', 'creative', 'operator', 'audience'] as string[]).includes(id)) {
    return personaLabel(id as PersonaId, lang)
  }
  return id
}

function backLink(L: (typeof LABELS)[RoundtableLang]): string {
  return `<p class="back"><a href="#top">${esc(L.backToTop)}</a></p>`
}

function sectionOpen(id: string, title: string, extraClass = ''): string {
  const cls = extraClass ? ` card ${extraClass}` : ' card'
  return `<section id="${esc(id)}" class="${cls.trim()}" tabindex="-1">
  <h2><a class="anchor" href="#${esc(id)}" aria-hidden="true">#</a>${esc(title)}</h2>`
}

