/** Build a single-file HTML report suitable for Chat artifact preview + browser. */
export function buildRoundtableReportHtml(data: RoundtableReportData): string {
  const lang = data.language
  const L = LABELS[lang]
  const when = data.generatedAt ?? new Date().toISOString()
  const issueTitle = data.issue.replace(/\s+/g, ' ').trim().slice(0, 80)

  const toc: TocItem[] = [
    { id: 'sec-issue', label: L.issue, depth: 1 },
    { id: 'sec-plan', label: L.plan, depth: 1 },
  ]

  for (const r of data.rounds) {
    const label = roundHeading(lang, r.round)
    const focus = r.focus.trim()
    toc.push({
      id: `sec-round-${r.round}`,
      label: focus ? `${label} · ${focus.slice(0, 36)}${focus.length > 36 ? '…' : ''}` : label,
      depth: 1,
    })
  }

  const edges = data.edges ?? []
  if (edges.length > 0) {
    toc.push({ id: 'sec-edges', label: L.edges, depth: 1 })
  }
  if (data.decision) {
    toc.push({ id: 'sec-decision', label: L.decision, depth: 1 })
  }

  const tocHtml = `
<nav class="toc" id="toc" aria-label="${esc(L.toc)}">
  <p class="toc-title">${esc(L.toc)}</p>
  <ol>
    ${toc
      .map(
        (item) =>
          `<li class="depth-${item.depth}"><a href="#${esc(item.id)}">${esc(item.label)}</a></li>`,
      )
      .join('\n    ')}
  </ol>
</nav>`

  const issueHtml = `
${sectionOpen('sec-issue', L.issue)}
  <div class="prose">${proseHtml(data.issue)}</div>
  ${backLink(L)}
</section>`

  const planHtml = `
${sectionOpen('sec-plan', L.plan)}
  <p class="meta"><strong>${esc(L.why)}:</strong> ${esc(data.rationale || '—')}</p>
  <h3>${esc(L.agenda)}</h3>
  <ol>${
    data.agenda.length
      ? data.agenda.map((a) => `<li>${esc(a)}</li>`).join('\n')
      : '<li class="muted">—</li>'
  }</ol>
  ${backLink(L)}
</section>`

  const roundsHtml = data.rounds
    .map((r) => {
      const speeches = r.speeches
        .map(
          (s) => `
        <article class="speech" id="sec-round-${r.round}-${esc(s.speaker)}">
          <h4>${esc(personaLabel(s.speaker, lang))}</h4>
          <div class="prose">${proseHtml(s.content)}</div>
        </article>`,
        )
        .join('\n')
      return `
${sectionOpen(`sec-round-${r.round}`, roundHeading(lang, r.round), 'round')}
  <p class="meta"><strong>${esc(L.focus)}:</strong> ${esc(r.focus)}</p>
  <h3>${esc(L.speeches)}</h3>
  <div class="speeches">${speeches || '<p class="muted">—</p>'}</div>
  <h3>${esc(L.stage)}</h3>
  <div class="stage">
    <p><strong>${esc(L.agreed)}</strong></p>
    <ul>${bullets(r.stage.agreed)}</ul>
    <p><strong>${esc(L.open)}</strong></p>
    <ul>${bullets(r.stage.open)}</ul>
    ${
      r.stage.earlyExit
        ? `<p class="badge">${esc(L.early)}${r.stage.earlyExitReason ? `: ${esc(r.stage.earlyExitReason)}` : ''}</p>`
        : ''
    }
  </div>
  ${backLink(L)}
</section>`
    })
    .join('\n')

  const edgesHtml =
    edges.length === 0
      ? ''
      : `
${sectionOpen('sec-edges', L.edges)}
  <ul class="edges">
    ${edges
      .map(
        (e) =>
          `<li><span class="from">${esc(personaName(e.from, lang))}</span>
           <span class="rel">${esc(edgeRel(lang, e.relation))}</span>
           <span class="to">${esc(personaName(e.to, lang))}</span>
           <span class="round-tag">R${e.round}</span>
           ${e.summary ? `<div class="sum">${esc(e.summary)}</div>` : ''}</li>`,
      )
      .join('\n')}
  </ul>
  ${backLink(L)}
</section>`

  const decide = data.decision
  const decideHtml = decide
    ? `
${sectionOpen('sec-decision', L.decision, 'decision')}
  <div class="prose lead">${proseHtml(decide.decision)}</div>
  <h3>${esc(L.residual)}</h3>
  <ul>${bullets(decide.residual)}</ul>
  <h3>${esc(L.next)}</h3>
  <ol>${
    decide.nextSteps.length
      ? decide.nextSteps.map((x) => `<li>${esc(x)}</li>`).join('\n')
      : '<li class="muted">—</li>'
  }</ol>
  ${data.earlyExit ? `<p class="badge">${esc(L.early)}</p>` : ''}
  ${backLink(L)}
</section>`
    : ''

  return `<!DOCTYPE html>
<html lang="${esc(lang)}">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <meta name="generator" content="hip-roundtable" />
  <title>${esc(L.title)} — ${esc(issueTitle)}</title>
  <style>
${ROUNDTABLE_REPORT_STYLES}
  </style>
</head>
<body>
  <a class="skip-link" href="#sec-issue">${esc(L.issue)}</a>
  <div class="layout" id="top">
    ${tocHtml}
    <main>
      <header class="report-header">
        <h1>${esc(L.title)}</h1>
        <p class="sub">${esc(when)}${data.earlyExit ? ` · ${esc(L.early)}` : ''}</p>
      </header>

      ${issueHtml}
      ${planHtml}
      ${roundsHtml}
      ${edgesHtml}
      ${decideHtml}

      <footer class="report-footer">${esc(L.footer)}</footer>
    </main>
  </div>
</body>
</html>
`
}

