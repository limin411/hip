#!/usr/bin/env node
/**
 * Generate packages/sidecar/src/session/ops/content.ts from packages/product-content/ops/ (SoT).
 *
 * Usage:
 *   node scripts/generate-ops-content.mjs
 *   node scripts/generate-ops-content.mjs --check
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const SOT = join(ROOT, 'packages', 'product-content', 'ops')
const OUT = join(ROOT, 'packages', 'sidecar', 'src', 'session', 'ops', 'content.ts')

function die(msg) {
  console.error(`[generate-ops-content] ${msg}`)
  process.exit(1)
}

function readText(p) {
  try {
    return readFileSync(p, 'utf8')
  } catch (e) {
    die(`missing file: ${relative(ROOT, p)} (${e.message})`)
  }
}

function asTemplateLiteral(s) {
  return s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')
}

function asSingleQuoted(s) {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

function build() {
  const meta = JSON.parse(readText(join(SOT, 'meta.json')))
  for (const k of ['skillId', 'skillName', 'skillVersion', 'description']) {
    if (typeof meta[k] !== 'string' || !meta[k].trim()) die(`meta.json missing string: ${k}`)
  }
  const skillBody = readText(join(SOT, 'hip-coding', 'SKILL.md')).replace(/\r\n/g, '\n').trimEnd() + '\n'
  const descEscaped = meta.description.replace(/"/g, '\\"')
  const skillMd =
    `---\nname: ${meta.skillName}\ndescription: "${descEscaped}"\n---\n\n` + skillBody

  const hash = createHash('sha256')
    .update(meta.skillVersion)
    .update('\0')
    .update(skillMd)
    .digest('hex')
    .slice(0, 16)

  const out = `/**
 * AUTO-GENERATED by scripts/generate-ops-content.mjs — DO NOT EDIT BY HAND.
 * Source of truth: packages/product-content/ops/
 * Regenerate: yarn product:content  (or node scripts/generate-ops-content.mjs)
 * Check:      yarn product:content:check
 *
 * contentHash=${hash} skillVersion=${meta.skillVersion}
 */

/** Materialization schema version (from packages/product-content/ops/meta.json). */
export const OPS_SKILL_VERSION = ${asSingleQuoted(meta.skillVersion)}

export const CODING_SKILL_ID = ${asSingleQuoted(meta.skillId)}
export const CODING_SKILL_NAME = ${asSingleQuoted(meta.skillName)}

export const CODING_SKILL_DESCRIPTION = ${asSingleQuoted(meta.description)}

/** Level-2 body (frontmatter + markdown). */
export const CODING_SKILL_MD = \`${asTemplateLiteral(skillMd)}\`

export const CODING_SKILL_FILES: ReadonlyArray<{ rel: string; body: string }> = [
  { rel: 'SKILL.md', body: CODING_SKILL_MD },
]
`
  return { out, hash, meta }
}

function main() {
  const check = process.argv.includes('--check')
  const { out, hash, meta } = build()
  if (check) {
    if (!existsSync(OUT)) die(`missing ${relative(ROOT, OUT)} — run yarn product:content`)
    if (readFileSync(OUT, 'utf8') !== out) {
      die(`ops content.ts is stale vs packages/product-content/ops/. Run: yarn product:content`)
    }
    console.log(`[generate-ops-content] ok (check) hash=${hash} skill=${meta.skillVersion}`)
    return
  }
  writeFileSync(OUT, out, 'utf8')
  console.log(`[generate-ops-content] wrote ${relative(ROOT, OUT)} hash=${hash} skill=${meta.skillVersion}`)
}

main()
